def sieve_fig(state, alt):
    """1~50 판. state: 'blank' | 'step2'(1 지우고 2 남기고 2의 배수 지움) | 'done'(체 완성)"""
    polys, texts, segs = [], [], []
    for k in range(1, 51):
        r, c = (k - 1) // 10, (k - 1) % 10
        x, y = c, -r
        keep = crossed = False
        fill = "FFFFFF"
        if state == "step2":
            keep = k == 2
            crossed = k == 1 or (k % 2 == 0 and k != 2)
        elif state == "done":
            keep = k in PRIMES
            crossed = k not in PRIMES
        if keep:
            fill = "F2C14E"
        elif crossed:
            fill = "EEF0F3"
        polys.append({"pts": [[x, y], [x + 1, y], [x + 1, y - 1], [x, y - 1]], "fill": fill, "width": 1.25})
        if crossed:
            segs.append({"from": [x + 0.12, y - 0.88], "to": [x + 0.88, y - 0.12], "width": 1.25, "color": "9AA5B1"})
        texts.append({"at": [x + 0.5, y - 0.5], "text": str(k), **({"bold": True} if keep else {"bold": False})})
    return {"type": "geo", "points": {}, "polygons": polys, "segments": segs, "texts": texts, "names": False, "alt": alt}


