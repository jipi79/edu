def two_lines(top, bottom, alt):
    """top/bottom: (jumps, end) — jumps: [(from, to, color, label)] 두 번 이동"""
    def build(spec, y):
        (j1, j2), end = spec
        jumps = [(j1[0], j1[1], 0.6, j1[2], j1[3]), (j2[0], j2[1], 1.2, j2[2], j2[3])]
        return numline(-6, 6, y=y, jumps=jumps, dots=[(end, j2[2])])
    fig = geo([build(top, 3.0), build(bottom, 0.0)], alt, bounds=BOUNDS)
    return fig


